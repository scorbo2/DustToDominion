"""NPC generator tool tests (spec 17, dev plan stages 1-9).

Stages 1-2 covered the tool's front door (argument surface, argument
validation, npc_generator.json loading) and random name drawing with
the output-dir uniqueness rule. Stage 3 added prompt assembly. Stage 5
wired the generation pipeline: per-NPC directory layout (``image.png``,
``metadata.json``, empty ``audio/``) and one ``sd-client.py``
subprocess per NPC. Stage 8 made every prompt part configurable: the
``common_characteristics``, ``female_characteristics`` and
``male_characteristics`` keys with their nested validation, per-
category merge and suppression rules. Stage 9 added the age stat:
``metadata.json`` carries ``sex`` and ``age`` as its only keys, the
age drawn from the range the *resolved "age" value* (the option drawn
from the "age" category) maps onto via case-insensitive first match,
with "unknown" when no keyword matches or the category is suppressed.
The Testing bullets these stages make testable:

- missing ``npc_generator.json``: warning logged, defaults used
- malformed/empty config Json: error and exit code 1
- top-level config Json that is not an object: error and exit code 1
- unrecognized config key, top level or nested in the characteristics
  objects: error and exit code 1
- missing expected config key: warning naming the key and the default
  in effect; not fatal (terse "Default values will be used" wording
  for the two aggregate characteristics keys)
- blank/empty ``image_style`` or ``common_characteristics`` in config:
  honored, default NOT restored
- characteristics objects that are not objects, categories that are
  not string arrays: error and exit code 1
- a missing expected category: silent, defaults filled in per category
- an empty category: silently skipped when forming the prompt
- user-specified characteristic values reach the prompt verbatim
- ``--width``/``--height`` beat config values when both are given
- no ``--output-dir``: error and exit code 2 (argparse convention)
- ``--config`` pointing at a nonexistent file: warning, continue
- a name file argument (or the tools/-side default) that is missing,
  empty, whitespace-only, a directory, or unreadable: exit code 1
- output dir missing, a file, or unwritable: exit code 1
- any argument value failing validation: error and exit code 2
- defaults: count 10, sex random, seed -1, file paths beside the tool
- a random name can be generated by drawing first and last name and
  checking for uniqueness
- 100 random name draws in a row for the same NPC fail the duplicate
  check: "Name pool exhausted! You need more names." (exit code 1)
- the sd-client.py invocation carries the spec's flags; a failed or
  interrupted generation is fatal (code 1, including exit 130) and
  cleans up the partial NPC directory without touching NPCs already
  generated; ``sd-client.py`` missing beside the tool is fatal
- a successful generation fills the NPC directory with ``image.png``,
  ``metadata.json`` (``sex`` and ``age`` as the only keys) and an
  empty ``audio/`` subdirectory
- each NPC's age is recorded correctly: the resolved "age" value
  selects one of the spec's four inclusive ranges by case-insensitive
  first match, an unmatched value or a suppressed "age" category
  records "unknown", and ages are always strings, never numbers
- without ``--debug`` stdout carries only the per-NPC "Generating..."
  announcements; with ``--debug`` the exact prompt used for each NPC
  follows on its own line (and matches what sd-client.py received)

Generation subprocesses never touch the real network: an autouse
fixture swaps the tool's ``SD_CLIENT_SCRIPT`` seam for a harmless
in-script fake, and the one end-to-end test drives the real
``sd-client.py`` against the in-process stub server from
``helpers_npc_generator_stub``.

The tool is stdlib-only, so none of the pygame/audio/persistence
machinery is involved; plain ``tmp_path`` + ``capsys`` carry everything.
"""
