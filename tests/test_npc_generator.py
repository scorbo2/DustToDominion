class _ChoiceScriptRandom(random.Random):
    """``random.Random`` subclass whose ``choice()`` replays a scripted
    index sequence instead of sampling: ``choice(seq) -> seq[script[n]]``.

    Running off the script is an error, so a test that miscounts the
    draws the pool consumes fails loudly instead of silently drifting
    back into randomness. ``choice_calls`` lets tests pin the exact
    rng-consumption contract documented on ``NamePool``."""

    def __init__(self, script: list[int]) -> None:
        super().__init__(0)
        self._script = list(script)
        self.choice_calls = 0

    def choice(self, seq):
        if self.choice_calls >= len(self._script):
            raise AssertionError(
                f"choice script exhausted after {self.choice_calls} calls"
            )
        index = self._script[self.choice_calls]
        self.choice_calls += 1
        return list(seq)[index]


class _RecordingRandom(random.Random):
    """``random.Random`` subclass that records every ``randint()`` call
    with its arguments while still drawing real values.

    Stage 9's rng contract is about WHICH range gets drawn from, and
    about not drawing at all for "unknown" - statistics would be a
    slow, flaky way to pin that, so the calls are captured verbatim
    instead. ``randint_calls`` mirrors ``_ChoiceScriptRandom``'s
    ``choice_calls`` for the same honesty purpose."""

    def __init__(self, seed: int = 0) -> None:
        super().__init__(seed)
        self.randint_calls: list[tuple[int, int]] = []

    def randint(self, a, b):
        self.randint_calls.append((a, b))
        return super().randint(a, b)


