def _write_name_files(tmp_path: Path) -> dict[str, Path]:
    """Three valid, distinct name files in tmp_path, keyed by the
    argparse dest each one is meant to feed. Four first names x four
    surnames = 16 unique full names, comfortably above the default
    --count of 10 (the male and female lists carry the SAME names, so
    they add no extra full-name combinations)."""
    paths = {}
    for dest, filename in (
        ("first_names_female", "female_names.txt"),
        ("first_names_male", "male_names.txt"),
        ("last_names", "last_names.txt"),
    ):
        path = tmp_path / filename
        path.write_text("Alpha\nBravo\nCharlie\nDelta\n", encoding="utf-8")
        paths[dest] = path
    return paths


def _name_file_args(files: dict[str, Path]) -> list[str]:
    return [
        "--first-names-female", str(files["first_names_female"]),
        "--first-names-male", str(files["first_names_male"]),
        "--last-names", str(files["last_names"]),
    ]


def _write_config(tmp_path: Path, content: str) -> Path:
    config_path = tmp_path / "npc_generator.json"
    config_path.write_text(content, encoding="utf-8")
    return config_path


def _base_args(tmp_path: Path, config_path: Path | None = None) -> list[str]:
    """A fully valid argv: existing writable output dir, three valid
    name files, and an explicit ``--config``.

    The explicit ``--config`` (defaulting to a nonexistent tmp file)
    keeps every test independent of whether a developer happens to have
    a real tools/npc_generator.json in their tree - that location is
    user territory, not the repo's."""
    (tmp_path / "npc-out").mkdir()
    if config_path is None:
        config_path = tmp_path / "absent_npc_generator.json"
    return [
        "--output-dir", str(tmp_path / "npc-out"),
        *_name_file_args(_write_name_files(tmp_path)),
        "--config", str(config_path),
    ]


# ------------------------------------------------------------------ #
# the sd-client.py seam: a harmless default for every test, a
# recording fake for the wiring tests
# ------------------------------------------------------------------ #

#: Stand-in for tools/sd-client.py: records its argv (one Json list per
#: line) to the file named by FAKE_SD_LOG, writes marker PNG bytes to
#: the -o target, and optionally exits non-zero on the Nth invocation
#: - after writing the partial image, so "partially filled directory"
#: cleanup is genuinely tested and not just implied.
_FAKE_SD_CLIENT_SOURCE = """\
import json
import os
import sys
from pathlib import Path

args = sys.argv[1:]
log_path = os.environ["FAKE_SD_LOG"]
with open(log_path, "a", encoding="utf-8") as log:
    log.write(json.dumps(args) + "\\n")
invocation = sum(1 for _ in open(log_path, encoding="utf-8"))
output = Path(args[args.index("-o") + 1])
output.write_bytes(b"\\x89PNG\\r\\n\\x1a\\n fake generated bytes")
fail_on_n = int(os.environ.get("FAKE_SD_FAIL_ON_N", "0"))
if fail_on_n and invocation == fail_on_n:
    sys.exit(int(os.environ.get("FAKE_SD_EXIT", "1")))
"""


@pytest.fixture(autouse=True)
def hermetic_sd_client(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """Redirect the tool's ``SD_CLIENT_SCRIPT`` at a do-nothing script
    for every test in this module: from stage 5 on, any valid run
    launches real subprocesses, and no test that is not explicitly
    about generation should reach the real ``tools/sd-client.py`` (or
    its default-server network attempt). Wiring tests override this by
    installing the recording fake via ``_fake_sd_client``."""
    harmless = tmp_path / "harmless_sd_client.py"
    harmless.write_text(
        "# exits 0 without touching the network or the -o target\n",
        encoding="utf-8",
    )
    monkeypatch.setattr(npc_generator_lib, "SD_CLIENT_SCRIPT", harmless)


def _fake_sd_client(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    *,
    fail_on_n: int = 0,
    exit_code: int = 1,
) -> Path:
    """Install the recording fake as the tool's SD_CLIENT_SCRIPT and
    return its invocation log path (empty at install time)."""
    script = tmp_path / "fake_sd_client.py"
    script.write_text(_FAKE_SD_CLIENT_SOURCE, encoding="utf-8")
    monkeypatch.setattr(npc_generator_lib, "SD_CLIENT_SCRIPT", script)
    log = tmp_path / "sd_client_invocations.jsonl"
    log.touch()
    monkeypatch.setenv("FAKE_SD_LOG", str(log))
    if fail_on_n:
        monkeypatch.setenv("FAKE_SD_FAIL_ON_N", str(fail_on_n))
        monkeypatch.setenv("FAKE_SD_EXIT", str(exit_code))
    return log


def _recorded_invocations(log: Path) -> list[list[str]]:
    """The fake's argv log, one argument list per invocation."""
    return [
        json.loads(line)
        for line in log.read_text(encoding="utf-8").splitlines()
    ]


def _flag_value(invocation: list[str], flag: str) -> str:
    """The value following ``flag`` in a recorded invocation."""
    return invocation[invocation.index(flag) + 1]


