class _InterruptingPopen:
    """``subprocess.Popen`` stand-in for the ctrl+C case: the first
    ``wait()`` dies on ``KeyboardInterrupt`` (the signal reached the
    tool itself), and a second ``wait()`` collects the child's real
    exit code."""

    def __init__(self, interrupt_first_wait: bool, child_code: int = 0) -> None:
        self._interrupt_first_wait = interrupt_first_wait
        self._child_code = child_code
        self._wait_count = 0

    def wait(self) -> int:
        self._wait_count += 1
        if self._interrupt_first_wait and self._wait_count == 1:
            raise KeyboardInterrupt()
        return self._child_code


def test_invoke_sd_client_withParentInterrupted_shouldReportTheChildsCodeNotOurOwn(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # GIVEN a Popen stand-in that dies on the first wait and answers
    # 130 on the second (sd-client's documented interrupt code):
    monkeypatch.setattr(
        npc_generator_lib.subprocess,
        "Popen",
        lambda command: _InterruptingPopen(True, 130),
    )

    # WHEN the tool collects the exit code, THEN the child's 130
    # survives the parent's KeyboardInterrupt instead of the parent's
    # own interrupt convention:
    returncode = npc_generator_lib._invoke_sd_client(["anything"])

    assert returncode == 130


